//! Read-only helper that generates an app-target.toml from a running herdr-core instance.
use crate::{Result, app};
use serde_json::Value;
use std::{
    io::Write,
    path::{Path, PathBuf},
};

const USAGE: &str = "usage: crewmoor app-target generate [--socket PATH] [--output PATH]";

pub fn cli(args: &[String]) -> Result<()> {
    match args.split_first() {
        Some((cmd, rest)) if cmd == "generate" => generate(rest),
        _ => Err(USAGE.into()),
    }
}

fn generate(args: &[String]) -> Result<()> {
    let opts = Opts::parse(args)?;
    let socket = opts.socket()?;
    let status = app::exchange(&socket, "server.status", serde_json::json!({}))?;
    let doc = app::exchange(&socket, "doc.get", serde_json::json!({"name":"herdr-app"}))?;
    let toml = render(&socket, &status, &doc)?;
    write_output(&opts.output, &toml)
}

fn render(socket: &Path, status: &Value, doc: &Value) -> Result<String> {
    let core_id = status["core"]["id"]
        .as_str()
        .ok_or("server.status missing core.id")?;
    let machine = status["core"]["name"]
        .as_str()
        .ok_or("server.status missing core.name")?;
    let version = status["version"]
        .as_str()
        .ok_or("server.status missing version")?;

    let mut out = format!(
        "# Generated by crewmoor app-target generate (hc {version})\n\
         # Review space_id and tab_id before use; omit both for project placement.\n\
         session   = \"default\"\n\
         socket    = \"{}\"\n\
         core_id   = \"{core_id}\"\n\
         machine   = \"{machine}\"\n",
        socket.display(),
    );

    append_spaces(&mut out, machine, doc);
    Ok(out)
}

fn append_spaces(out: &mut String, machine: &str, doc: &Value) {
    let spaces = match doc["value"]["spaces"].as_array() {
        Some(s) if !s.is_empty() => s,
        _ => return,
    };
    out.push_str("\n# Available spaces and tabs (uncomment to use):\n");
    for space in spaces {
        let sid = space["id"].as_str().unwrap_or("");
        let sname = space["name"].as_str().unwrap_or("");
        let label = if sname.is_empty() { sid } else { sname };
        out.push_str(&format!("# space: {label}\n"));
        if let Some(tabs) = space["tabs"].as_array() {
            for tab in tabs {
                let tid = tab["id"].as_str().unwrap_or("");
                let tname = tab["name"].as_str().unwrap_or("");
                let tlabel = if tname.is_empty() { tid } else { tname };
                let local_sid = sid.strip_prefix(&format!("{machine}/")).unwrap_or(sid);
                let local_tid = tid.strip_prefix(&format!("{machine}/")).unwrap_or(tid);
                out.push_str(&format!(
                    "# space_id = \"{local_sid}\"  # {label}\n\
                     # tab_id   = \"{local_tid}\"  # {tlabel}\n"
                ));
            }
        }
    }
}

fn write_output(output: &Option<PathBuf>, content: &str) -> Result<()> {
    match output {
        Some(path) => {
            let mut f = std::fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .open(path)
                .map_err(|e| format!("cannot create {}: {e}", path.display()))?;
            f.write_all(content.as_bytes())?;
            println!("written: {}", path.display());
        }
        None => print!("{content}"),
    }
    Ok(())
}

struct Opts {
    socket: Option<PathBuf>,
    output: Option<PathBuf>,
}

impl Opts {
    fn parse(args: &[String]) -> Result<Self> {
        let mut socket: Option<PathBuf> = None;
        let mut output: Option<PathBuf> = None;
        let mut iter = args.iter();
        loop {
            match iter.next().map(|s| s.as_str()) {
                None => break,
                Some("--socket") => {
                    socket = Some(iter.next().ok_or("--socket needs a value")?.into());
                }
                Some("--output") => {
                    output = Some(iter.next().ok_or("--output needs a value")?.into());
                }
                _ => return Err(USAGE.into()),
            }
        }
        Ok(Self { socket, output })
    }

    fn socket(&self) -> Result<PathBuf> {
        if let Some(p) = &self.socket {
            return Ok(p.clone());
        }
        let base = std::env::var("XDG_RUNTIME_DIR")
            .map(PathBuf::from)
            .unwrap_or_else(|_| PathBuf::from("/run/user/1000"));
        Ok(base.join("herdr-core").join("default.sock"))
    }
}
