//! Read-only discovery fills factual fields; task choices come only from the template.
use super::{Role, Team};
use crate::{
    Result, app, app_target,
    config::{self, AgentKind, Host, Runtime},
    feedback::{Evidence, model},
    native, transport,
};
use serde::Deserialize;
use serde_json::Value;
use std::{
    env, fs,
    os::unix::fs::PermissionsExt,
    path::{Path, PathBuf},
    time::Duration,
};

const USAGE: &str = "usage: crewmoor team generate TEMPLATE [--output NEW_TEAM.toml]";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Template {
    team: String,
    task: String,
    runtime: Runtime,
    runtime_binary: Option<PathBuf>,
    #[serde(rename = "runtime_version")]
    _runtime_version: Option<String>,
    host: Option<HostInput>,
    app_target: Option<PathBuf>,
    feedback_registry: PathBuf,
    evidence: Evidence,
    dispatcher: String,
    roles: Vec<RoleInput>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct HostInput {
    socket: PathBuf,
    #[serde(rename = "server_version")]
    _server_version: Option<String>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RoleInput {
    role: String,
    cwd: PathBuf,
    agent: AgentKind,
    agent_executable: Option<PathBuf>,
    #[serde(rename = "agent_version")]
    _agent_version: Option<String>,
    #[serde(default)]
    agent_args: Vec<String>,
    initial_prompt: Option<String>,
    message_constraint: Option<String>,
    tab_id: Option<String>,
    opencode: Option<crate::opencode::Options>,
}

struct Discovered {
    host: Option<Host>,
    server_version: String,
    layout: Option<Value>,
}

pub(super) fn cli(args: &[String]) -> Result<()> {
    let (template, output) = match args {
        [template] => (template, None),
        [template, flag, output] if flag == "--output" => (template, Some(PathBuf::from(output))),
        _ => return Err(USAGE.into()),
    };
    let template: Template = toml::from_str(&fs::read_to_string(template)?)?;
    let content = generate(template)?;
    app_target::write_output(&output, &content)
}
fn generate(input: Template) -> Result<String> {
    let command = match input.runtime {
        Runtime::Tui => "herdr",
        Runtime::Core => "hc",
    };
    let runtime_binary = executable(input.runtime_binary.as_deref(), command)?;
    let runtime_version = version(&runtime_binary)?;
    let found = connection(&input, &runtime_binary, &runtime_version)?;
    let roles = input
        .roles
        .into_iter()
        .map(role)
        .collect::<Result<Vec<_>>>()?;
    let team = Team {
        team: input.team,
        task: input.task,
        runtime: input.runtime,
        runtime_binary,
        runtime_version,
        host: found.host,
        app_target: input.app_target,
        feedback_registry: input.feedback_registry,
        evidence: input.evidence,
        dispatcher: input.dispatcher,
        roles,
    };
    render(team, found.server_version, found.layout)
}
fn render(team: Team, server_version: String, layout: Option<Value>) -> Result<String> {
    team.validate()?;
    validate_launches(&team)?;
    if let Some(layout) = layout {
        team.check_placement(&mut |_| Ok(layout.clone()))?;
    }
    let serialized = toml::to_string(&team)?;
    Ok(format!(
        "# Generated by crewmoor team generate; review task and placement choices.\n# Runtime server version: {} (client runtime_version is separate).\n{}",
        server_version, serialized
    ))
}
fn validate_launches(team: &Team) -> Result<()> {
    for role in &team.roles {
        // A validation-only copy: no instance is invented and no store is created.
        // The future team-start STATE is not a generation input; only absoluteness matters here.
        let mut config = team.launch_config(role, &team.feedback_registry, None)?;
        config.resolve_target()?;
        config.validate()?;
    }
    Ok(())
}
fn connection(input: &Template, binary: &Path, client: &str) -> Result<Discovered> {
    match (&input.runtime, &input.host, &input.app_target) {
        (Runtime::Tui, Some(host), None) => {
            let host = tui(binary, &host.socket)?;
            let version = host.server_version.clone();
            Ok(Discovered {
                host: Some(host),
                server_version: version,
                layout: None,
            })
        }
        (Runtime::Core, None, Some(target)) => {
            let (server_version, layout) = core(target, client)?;
            Ok(Discovered {
                host: None,
                server_version,
                layout: Some(layout),
            })
        }
        _ => Err("template needs tui + host.socket, or core + existing app_target".into()),
    }
}
fn tui(binary: &Path, socket: &Path) -> Result<Host> {
    config::absolute(socket)?;
    let status = tui_status(binary, socket)?;
    tui_host(socket, &status)
}
fn tui_status(binary: &Path, socket: &Path) -> Result<Value> {
    let mut command = native::endpoint_command(binary, socket);
    let output = transport::output(
        command.args(["status", "server", "--json"]),
        Duration::from_secs(10),
    )?;
    if !output.status.success() {
        return Err("TUI status server query failed; no team generated".into());
    }
    Ok(serde_json::from_slice(&output.stdout)?)
}
fn tui_host(socket: &Path, status: &Value) -> Result<Host> {
    if status["running"] != true {
        return Err("selected TUI server is not running".into());
    }
    let actual_socket = PathBuf::from(native::text(status, "/socket")?);
    same_socket(socket, &actual_socket)?;
    let server_version = native::text(status, "/version")?;
    model::identifier(&server_version)?;
    Ok(Host {
        socket: actual_socket,
        server_version,
    })
}
fn same_socket(selected: &Path, actual: &Path) -> Result<()> {
    config::absolute(actual)?;
    if actual.canonicalize()? != selected.canonicalize()? {
        return Err("TUI status returned a different socket".into());
    }
    Ok(())
}
fn core(target: &Path, client: &str) -> Result<(String, Value)> {
    let app = core_target(target)?;
    let (status, doc) = app_target::discover(&app.socket)?;
    let server = core_version(&app, &status, client)?;
    app::check_host_processes(&native::identity_from(&status)?, &status)?;
    if app.space_id.is_some() {
        app::existing_layout(&app, &doc)?;
    }
    Ok((server, doc))
}
fn core_target(target: &Path) -> Result<app::Binding> {
    config::absolute(target)?;
    let app: app::Binding = toml::from_str(&fs::read_to_string(target)?)?;
    app.validate(&Runtime::Core)?;
    Ok(app)
}
fn core_version(app: &app::Binding, status: &Value, client: &str) -> Result<String> {
    if native::text(status, "/core/id")? != app.core_id {
        return Err("existing app_target core identity is stale; regenerate it explicitly".into());
    }
    let server = native::text(status, "/version")?;
    model::identifier(&server)?;
    if client.strip_prefix("hc ") != Some(server.as_str()) {
        return Err(
            "core client/server versions differ; current team start/bind requires equal versions"
                .into(),
        );
    }
    Ok(server)
}
fn role(input: RoleInput) -> Result<Role> {
    config::absolute(&input.cwd)?;
    if !input.cwd.is_dir() {
        return Err("role cwd is not an existing directory".into());
    }
    config::validate_args(&input.agent, &input.agent_args)?;
    config::initial_prompt(&input.agent, input.initial_prompt.as_deref())?;
    let agent_executable = executable(input.agent_executable.as_deref(), input.agent.name())?;
    let agent_version = version(&agent_executable)?;
    Ok(Role {
        role: input.role,
        cwd: input.cwd,
        agent: input.agent,
        agent_executable,
        agent_version,
        agent_args: input.agent_args,
        initial_prompt: input.initial_prompt,
        message_constraint: input.message_constraint,
        tab_id: input.tab_id,
        opencode: input.opencode,
    })
}
fn version(binary: &Path) -> Result<String> {
    let version = native::version(binary)?;
    model::identifier(&version)?;
    Ok(version)
}
fn executable(hint: Option<&Path>, default: &str) -> Result<PathBuf> {
    if let Some(path) = hint {
        return require_executable(path);
    }
    let path = env::var_os("PATH").ok_or("PATH is unset; provide an explicit executable")?;
    let found = env::split_paths(&path)
        .map(|dir| dir.join(default))
        .find(|path| is_executable(path))
        .ok_or_else(|| format!("executable {default} not found on PATH"))?;
    require_executable(&found)
}
fn is_executable(path: &Path) -> bool {
    fs::metadata(path).is_ok_and(|m| m.is_file() && m.permissions().mode() & 0o111 != 0)
}
fn require_executable(path: &Path) -> Result<PathBuf> {
    if !is_executable(path) {
        return Err(format!("not an executable file: {}", path.display()).into());
    }
    Ok(path.canonicalize()?)
}
